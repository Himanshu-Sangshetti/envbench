"""Generate the hand-audit section of the paper from the labels.

The numbers in this section come from a human-in-the-loop (or model-in-the-loop)
label set, so they are exactly the kind of figure that drifts when it is typed
by hand. This script writes the section as LaTeX, with every number filled in
from the analysis, and the paper includes it with \\input. The build gate
regenerates it, so the section and the labels cannot disagree.

    python scripts/make_audit_section.py
"""

from __future__ import annotations

import collections
import json
import math
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from scorer import load  # noqa: E402

OUT = Path("../paper/generated_audit.tex")
FP = {"fp_possible", "fp_possible_but_hard"}


def wilson(k, n, z=1.96):
    if n == 0:
        return (float("nan"), float("nan"))
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, c - h), min(1.0, c + h))


def main() -> int:
    rows = load("results/envbench/envbench_registry.csv")
    by_id = {r["env_id"]: r for r in rows}
    N = len(rows)

    manifest = json.loads(Path("results/hand_audit/sample.json").read_text())
    labels = {}
    for m in manifest:
        f = Path(m["packet_dir"]) / "label.json"
        if f.exists():
            try:
                labels[m["env_id"]] = json.loads(f.read_text())
            except json.JSONDecodeError:
                pass

    def stratum_of(r):
        s = float(r["fragility_score_strict"])
        if s >= 0.4:
            return "flagged_severe"
        if s >= 0.2:
            return "flagged_fragile"
        if float(r["fragility_score"]) >= 0.2:
            return "full_score_only"
        return "unflagged_clean"

    pop = collections.Counter(stratum_of(r) for r in rows)
    by_stratum = collections.defaultdict(lambda: [0, 0])
    for m in manifest:
        l = labels.get(m["env_id"])
        if not l:
            continue
        by_stratum[m["stratum"]][1] += 1
        by_stratum[m["stratum"]][0] += int(l["verdict"] in FP)

    est = sum((pop[s] / N) * (k / n) for s, (k, n) in by_stratum.items() if n)
    var = sum(((pop[s] / N) ** 2) * (k / n) * (1 - k / n) / n
              for s, (k, n) in by_stratum.items() if n)
    se = math.sqrt(var)
    lo, hi = max(0.0, est - 1.96 * se), min(1.0, est + 1.96 * se)
    pattern = sum(1 for r in rows if float(r["fragility_score_strict"]) >= 0.2) / N

    mode_n = collections.Counter()
    mode_fp = collections.Counter()
    for m in manifest:
        l = labels.get(m["env_id"])
        r = by_id.get(m["env_id"])
        if not l or r is None:
            continue
        real = l["verdict"] in FP
        for cell in (r.get("defect_modes") or "").split("|"):
            md = cell.split(" x")[0].strip()
            if md:
                mode_n[md] += 1
                mode_fp[md] += int(real)

    cal = {}
    _c = Path("results/detector_calibration.json")
    if _c.exists():
        cal = json.loads(_c.read_text())
    cal_auroc = cal.get("calibration", {}).get("auroc_oof", float("nan"))
    _ci = cal.get("calibration", {}).get("auroc_ci", [float("nan")] * 2)
    cal_auroc_lo, cal_auroc_hi = _ci

    def pct(x, d=1):
        """A LaTeX-safe percentage: the % must be escaped or it comments out
        the rest of the line and swallows a closing brace."""
        return f"{x:.{d}f}\\%"

    def ppc(k, n):
        p = k / n if n else float("nan")
        a, b = wilson(k, n)
        return f"{p:.2f} [{a:.2f}, {b:.2f}]"

    lines = []
    lines.append("% GENERATED by scripts/make_audit_section.py -- do not edit by hand.")
    lines.append(f"\\subsection{{A hand audit: how much of the pattern rate is real?}}")
    lines.append(r"\label{sec:audit}")
    lines.append("")
    lines.append(
        "A static detector over source text invites the obvious objection: that the patterns it fires on "
        "are common in correct code. We answer that by hand. We drew a stratified sample of "
        f"{len(manifest)} environments from the registry (seeded, and pre-specified in "
        "\\texttt{scripts/hand\\_audit\\_sample.py}), and had each verifier read and judged on one "
        "question: \\emph{can a plausible-but-wrong answer receive full reward?} The auditors saw the "
        "verifier source and the task description and nothing else---not the detector's score, not its "
        "flags, and not the family---so the labels are a function of the code rather than of the "
        "detector.")
    lines.append("")
    lines.append(
        f"The answer is that the pattern rate and the exploitable rate are not the same quantity. "
        f"Across the {len(labels)} environments judged, the fraction with a real false-positive path is "
        f"\\textbf{{{pct(est)}}} (95\\p{{}} CI {pct(lo)}--{pct(hi)}) once the stratified sample is "
        f"reweighted to the registry, against the \\textbf{{{pct(pattern)}}} pattern rate the static "
        f"detector reports. Per-mode precision spans the whole range:")
    lines.append("")
    lines.append("\\begin{table}[t]")
    lines.append("\\centering")
    lines.append("\\small")
    lines.append("\\begin{tabular}{@{}p{4.4cm}rr@{}}")
    lines.append("\\toprule")
    lines.append("\\textbf{Defect mode} & \\textbf{$n$} & \\textbf{precision} \\\\")
    lines.append("\\midrule")
    short = {
        "LLM judge without reference anchoring": "LLM judge, no reference",
        "startswith/endswith": "startswith / endswith",
        "set_membership": "set membership",
        "test suite without executing candidate": "test suite not executed",
        "substring_match": "substring match",
        "unnormalised string equality": "unnormalised string equality",
        "float equality without tolerance": "float equality, no tolerance",
        "hardcoded answer literals": "hardcoded answer literals",
        "regex numeric extraction": "regex numeric extraction",
    }
    for md, n in mode_n.most_common():
        lines.append(f"{short.get(md, md)} & {n} & {ppc(mode_fp[md], n)} \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append(
        "\\caption{Per-mode precision of the static detector, from the hand audit: of the sampled "
        "environments the detector flags with each mode, the fraction an auditor judged to have a "
        "real false-positive path. Two modes carry essentially no signal, and the two with the most "
        "signal are the ones that check the answer rather than the format.}")
    lines.append("\\label{tab:audit-modes}")
    lines.append("\\end{table}")
    lines.append("")
    lines.append(
        "The consequence is stated plainly, because it is the paper's main negative result: "
        "\\textbf{knowing which of the nine source patterns a verifier contains does not tell you "
        "whether it can be gamed.} Refitting the detector on the audited labels and cross-validating "
        "gives an out-of-fold AUROC of "
        f"{cal_auroc:.2f} (95\\p{{}} CI {cal_auroc_lo:.2f}--{cal_auroc_hi:.2f}) for predicting "
        f"audited false-positive risk---"
        + ("at or below chance" if cal_auroc_hi <= 0.52 else
           "indistinguishable from chance" if cal_auroc_lo <= 0.52 else
           "close to chance")
        + ". The modes are not a measurement of exploitability; they are a measurement of which "
        "idioms an author wrote. \\emph{Unnormalised string equality} is the clearest case: it is a "
        "false \\emph{negative} risk (the verifier rejects a correct answer that differs in "
        "formatting), not a false-positive one, and the audit finds an exploitable path in "
        f"{mode_fp.get('unnormalised string equality', 0)} of the "
        f"{mode_n.get('unnormalised string equality', 0)} sampled environments that carry it. "
        "Reporting it as a fragility mode was a mistake, and the audit is what caught it.")
    # ── inter-rater agreement, if the second blind pass has been run ──
    _ag = Path("results/hand_audit/rerun/agreement.json")
    if _ag.exists():
        ag = json.loads(_ag.read_text())
        lines.append("")
        lines.append(
            f"The labels are not human expert judgement: the auditors are model instances applying "
            f"the rubric. We therefore measured their reliability directly, by labelling "
            f"{ag['n']} of the audited environments a second time, blind to the first pass. The two "
            f"passes agree on the verdict for {ag['raw_5way']:.0%} of environments "
            f"(Cohen's $\\kappa={ag['kappa_5way']:.2f}$), and on the coarser question this section "
            f"uses---does the verifier have a false-positive path?---for {ag['raw_binary']:.0%} "
            f"($\\kappa={ag['kappa_binary']:.2f}$). The numbers below should be read with that "
            f"agreement in mind.")
    lines.append("")
    lines.append(
        "Two things follow. The registry-wide prevalence of verifiers that can be fooled by a "
        f"plausible-but-wrong answer is around \\textbf{{{est:.0f}\\%}} (95\\p{{}} CI "
        f"{lo:.0f}--{hi:.0f}\\%): a large fraction of the supply, but smaller than the pattern "
        "count suggests, and not identifiable from metadata. And the cheap screen is not enough, "
        "which is the argument for the causal study in \\S\\ref{sec:next} rather than an argument "
        "against the premise: what a training run needs to know is not which idioms a verifier "
        "contains but whether it pays for a wrong answer.")
    lines.append("")

    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(lines)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
